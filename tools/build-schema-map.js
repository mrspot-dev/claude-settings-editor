#!/usr/bin/env node
// tools/build-schema-map.js
// Builds the SCHEMA_MAP block embedded in claude-settings-editor.html from two local sources:
//   tools/sources/claude-code-settings.schema.json  SchemaStore (Apache-2.0) — description text is embedded
//   tools/sources/settings-reference.md             code.claude.com docs — facts only, no prose, not committed
// Usage: node tools/build-schema-map.js [--fetch] [--dry]
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(__dirname, 'sources');
const HTML = path.join(ROOT, 'claude-settings-editor.html');
const SCHEMA_FILE = path.join(SRC, 'claude-code-settings.schema.json');
const REFERENCE_FILE = path.join(SRC, 'settings-reference.md');
const FETCHED_FILE = path.join(SRC, 'fetched.json');
const SCHEMA_URL = 'https://www.schemastore.org/claude-code-settings.json';
const REFERENCE_URL = 'https://code.claude.com/docs/en/settings-reference.md';
const START = '// @@SCHEMA_MAP_START';
const END = '// @@SCHEMA_MAP_END';
const LICENSE = 'Key descriptions (desc) from SchemaStore, Apache License 2.0 — see tools/sources/NOTICE-schemastore.txt. Facts (scope/type/default) from the Claude Code settings reference; no reference prose is embedded.';

const SCOPES = { 'Any file': 'any', 'Managed': 'managed', 'User or managed': 'user-managed', 'Global config': 'global-config', 'User, local, or managed': 'user-local-managed' };
const TYPES = ['string', 'boolean', 'number', 'integer', 'object', 'array'];
const ENV_RE = /`((?:CLAUDE|ANTHROPIC|DISABLE|ENABLE|AWS|GOOGLE|GCP|OTEL|MCP|MAX|HTTP|HTTPS|NO|USE|FORCE|SSL|NODE)_[A-Z0-9_]{2,})`/g;
const BAD_KEYS = new Set(['__proto__', 'constructor', 'prototype', '$schema']);

function schemaVersionOf(text) {
  const found = [...String(text).matchAll(/v(2\.\d+\.\d+)/g)].map(m => m[1]);
  return found.sort((a, b) => { const x = a.split('.').map(Number), y = b.split('.').map(Number); return (x[0] - y[0]) || (x[1] - y[1]) || (x[2] - y[2]); }).pop() || '';
}

function parseReference(md) {
  const parts = String(md).replace(/\r\n/g, '\n').split(/^### `([A-Za-z0-9.]+)`[ \t]*$/m);
  const facts = {};
  for (let i = 1; i < parts.length; i += 2) {
    const key = parts[i];
    if (BAD_KEYS.has(key)) continue;
    const body = parts[i + 1].split(/^## /m)[0];
    const scopeRaw = (body.match(/^\* \*\*Scope\*\*: \[`([^`]+)`\]/m) || [])[1] || '';
    const typeBlock = (body.match(/^\* \*\*Type\*\*: [\s\S]*?(?=\n\* \*\*|\n\n)/m) || [''])[0];
    const typeWord = ((typeBlock.match(/\*\*Type\*\*: ([A-Za-z]+)/) || [])[1] || '').toLowerCase();
    const defLine = (body.match(/^\* \*\*Default\*\*: ([^\n]+)/m) || [])[1] || '';
    // A closed set describes the key itself only when the key holds a string; on an object or array
    // key the "one of" list belongs to a nested field (modelSettings.effortLevel, spinnerVerbs.mode).
    const closedSet = /\b(?:one of|either|the string)\b/i.test(typeBlock) && !(TYPES.includes(typeWord) && typeWord !== 'string');
    const enumVals = closedSet ? [...typeBlock.matchAll(/`"([^"`]+)"`/g)].map(m => m[1]).filter((v, i, a) => a.indexOf(v) === i) : [];
    const since = (body.match(/Requires Claude Code v(\d+\.\d+\.\d+)/) || [])[1] || '';
    const env = [...body.matchAll(ENV_RE)].map(m => m[1]).filter((v, i, a) => a.indexOf(v) === i).slice(0, 4);
    facts[key] = {
      scope: SCOPES[scopeRaw] || 'unknown',
      type: TYPES.includes(typeWord) ? typeWord : '',
      enum: enumVals,
      default: defLine.replace(/\*\*/g, '').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/`/g, '').trim().slice(0, 80),
      since,
      env,
    };
  }
  return facts;
}

function buildMap(schema, facts, meta) {
  const props = (schema && schema.properties) || {};
  const names = new Set([...Object.keys(props), ...Object.keys(facts)].filter(k => !BAD_KEYS.has(k)));
  const keys = {};
  for (const key of [...names].sort()) {
    const p = Object.prototype.hasOwnProperty.call(props, key) ? props[key] : null;
    const f = Object.prototype.hasOwnProperty.call(facts, key) ? facts[key] : null;
    const desc = p && typeof p.description === 'string' ? p.description.replace(/\s+/g, ' ').trim() : '';
    keys[key] = {
      scope: f ? f.scope : 'unknown',
      type: (f && f.type) || (p && typeof p.type === 'string' && TYPES.includes(p.type) ? p.type : ''),
      enum: f && f.enum.length ? f.enum : (p && Array.isArray(p.enum) ? p.enum.map(String) : []),
      default: f ? f.default : (p && Object.prototype.hasOwnProperty.call(p, 'default') ? JSON.stringify(p.default) : ''),
      since: f ? f.since : '',
      env: f ? f.env : [],
      deprecated: !!p && (p.deprecated === true || /^\s*(?:\*\*)?DEPRECATED\b/i.test(desc)),
      desc,
      inSchema: !!p,
      inReference: !!f,
    };
  }
  return { meta: { ...meta, license: LICENSE }, keys };
}

function renderBlock(map) {
  const json = JSON.stringify(map).replace(/<\//g, '<\\/');
  return START + ' (generated by tools/build-schema-map.js — do not edit by hand)\n      const SCHEMA_MAP = ' + json + ';\n      ' + END;
}

function injectBlock(html, block) {
  const eol = (html.match(/\r\n/g) || []).length >= (html.match(/[^\r]\n/g) || []).length ? '\r\n' : '\n';
  const lf = String(html).replace(/\r\n/g, '\n');
  const re = /^([ \t]*)\/\/ @@SCHEMA_MAP_START[\s\S]*?\/\/ @@SCHEMA_MAP_END[^\n]*/m;
  if (!re.test(lf)) throw new Error('SCHEMA_MAP marker pair not found in HTML');
  const out = lf.replace(re, (m, indent) => block.split('\n').map((l, i) => (i === 0 ? indent + l : l)).join('\n'));
  return out.replace(/\n/g, eol);
}

async function fetchSources() {
  fs.mkdirSync(SRC, { recursive: true });
  const today = new Date().toISOString().slice(0, 10);
  const s = await fetch(SCHEMA_URL); if (!s.ok) throw new Error('schema fetch ' + s.status);
  const schemaText = await s.text();
  fs.writeFileSync(SCHEMA_FILE, JSON.stringify(JSON.parse(schemaText), null, 2) + '\n');
  const r = await fetch(REFERENCE_URL, { headers: { 'User-Agent': 'claude-settings-editor build' } }); if (!r.ok) throw new Error('reference fetch ' + r.status);
  fs.writeFileSync(REFERENCE_FILE, await r.text());
  const fetched = { schemaFetched: today, referenceFetched: today, referenceLastModified: r.headers.get('last-modified') || '', schemaVersion: schemaVersionOf(schemaText) };
  fs.writeFileSync(FETCHED_FILE, JSON.stringify(fetched, null, 2) + '\n');
  return fetched;
}

async function main(argv) {
  if (argv.includes('--fetch')) console.log('fetched', await fetchSources());
  for (const f of [SCHEMA_FILE, REFERENCE_FILE, FETCHED_FILE]) if (!fs.existsSync(f)) throw new Error('missing ' + path.relative(ROOT, f) + ' — run with --fetch');
  const schemaText = fs.readFileSync(SCHEMA_FILE, 'utf8');
  const fetched = JSON.parse(fs.readFileSync(FETCHED_FILE, 'utf8'));
  const map = buildMap(JSON.parse(schemaText), parseReference(fs.readFileSync(REFERENCE_FILE, 'utf8')), {
    schemaVersion: schemaVersionOf(schemaText), schemaFetched: fetched.schemaFetched, referenceFetched: fetched.referenceFetched,
    referenceLastModified: fetched.referenceLastModified, schemaSource: SCHEMA_URL, referenceSource: REFERENCE_URL,
  });
  const keys = Object.values(map.keys);
  console.log(`keys: ${keys.length} (schema ${keys.filter(k => k.inSchema).length}, reference ${keys.filter(k => k.inReference).length}, deprecated ${keys.filter(k => k.deprecated).length}, managed ${keys.filter(k => k.scope === 'managed').length}), schema ${map.meta.schemaVersion}`);
  const block = renderBlock(map);
  console.log(`block size: ${(block.length / 1024).toFixed(1)} KB`);
  if (argv.includes('--dry')) return;
  fs.writeFileSync(HTML, injectBlock(fs.readFileSync(HTML, 'utf8'), block));
  console.log('written into', path.relative(ROOT, HTML));
}

module.exports = { parseReference, buildMap, renderBlock, injectBlock, schemaVersionOf, START, END, SCHEMA_URL, REFERENCE_URL };
if (require.main === module) main(process.argv.slice(2)).catch(e => { console.error(e.message); process.exit(1); });
